/* Artwork.
   1. Original Rizolopy illustrations (src/assets/svg, generated by `npm run art` from tools/art/):
      character portraits and an emblem for every place, corner and card.
   2. Fallback: Microsoft Fluent Emoji 3D (MIT licence, see LICENSES.md) in src/assets/art for any
      other emoji. Used as Phaser textures and swapped in for emoji in the HTML UI. */
import manifest from "./assets/svg/manifest.json";

const files = import.meta.glob("./assets/art/*.webp", { eager: true, query: "?url", import: "default" });
// SVGs are imported as text and turned into base64 data URLs, which both <img> and Phaser's SVG loader accept.
const svgFiles = import.meta.glob("./assets/svg/*.svg", { eager: true, query: "?raw", import: "default" });
const svgByName = {};
for (const [path, raw] of Object.entries(svgFiles)) {
  svgByName[path.split("/").pop().replace(".svg", "")] = "data:image/svg+xml;base64," + btoa(unescape(encodeURIComponent(raw)));
}
const strip = e => e.replace(/\uFE0F/g, "");
const emojiToSvg = {};
for (const [e, name] of Object.entries(manifest.emoji)) emojiToSvg[strip(e)] = name;

const byCode = {};
for (const [path, url] of Object.entries(files)) {
  const code = path.split("/").pop().replace(".webp", "");
  byCode[code] = url;
}

function codeOf(emoji) {
  return [...emoji].map(ch => ch.codePointAt(0).toString(16)).filter(c => c !== "fe0f").join("-");
}

export function artUrl(emoji) {
  const name = emojiToSvg[strip(emoji)];
  if (name && svgByName[name]) return svgByName[name];
  return byCode[codeOf(emoji)] || null;
}
export function artKey(emoji) {
  const name = emojiToSvg[strip(emoji)];
  if (name && svgByName[name]) return "svg-" + name;
  const c = codeOf(emoji);
  return byCode[c] ? "art-" + c : null;
}
export const charKey = id => "char-" + id;
export const portraitUrl = id => svgByName["char-" + id];
/** An <img> of a character's portrait, for HTML templates. */
export const portrait = c => `<img class="portrait" src="${portraitUrl(c.id)}" alt="" draggable="false">`;

export const ALL_ART = [
  ...Object.entries(byCode).map(([code, url]) => ({ key: "art-" + code, url })),
  ...Object.entries(svgByName).map(([name, url]) => ({
    key: name.startsWith("char-") ? name : "svg-" + name, url, svg: true, size: name.startsWith("char-") ? 256 : 192,
  })),
];

/* Replace emoji characters in the page with the 3D artwork, like twemoji does. */
const EMOJI_RE = /\p{Extended_Pictographic}️?/gu;

function swapTextNode(node) {
  const text = node.nodeValue;
  EMOJI_RE.lastIndex = 0;
  if (!EMOJI_RE.test(text)) return;
  EMOJI_RE.lastIndex = 0;
  const frag = document.createDocumentFragment();
  let last = 0, m, changed = false;
  while ((m = EMOJI_RE.exec(text))) {
    const url = artUrl(m[0]);
    if (!url) continue;
    changed = true;
    if (m.index > last) frag.appendChild(document.createTextNode(text.slice(last, m.index)));
    const img = document.createElement("img");
    img.className = "emo";
    img.src = url;
    img.alt = m[0];
    img.draggable = false;
    frag.appendChild(img);
    last = m.index + m[0].length;
  }
  if (!changed) return;
  if (last < text.length) frag.appendChild(document.createTextNode(text.slice(last)));
  node.parentNode.replaceChild(frag, node);
}

function swapIn(root) {
  if (root.nodeType === 3) { if (root.parentNode && !root.parentNode.closest("input,textarea,canvas,title,script,style")) swapTextNode(root); return; }
  if (root.nodeType !== 1 || root.matches("input,textarea,canvas,script,style")) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(n => n.parentNode && !n.parentNode.closest("input,textarea,canvas,script,style") && swapTextNode(n));
}

export function startEmojiArt() {
  swapIn(document.body);
  new MutationObserver(muts => {
    for (const m of muts) {
      if (m.type === "characterData") swapIn(m.target);
      m.addedNodes.forEach(swapIn);
    }
  }).observe(document.body, { childList: true, subtree: true, characterData: true });
}
